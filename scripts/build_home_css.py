#!/usr/bin/env python3
"""Concatenate homepage page_css sources into static/css/home-page-bundle.css.

Order must match templates/pages/home.html (DEBUG branch). Do not include
base-bundle.css or fonts.css — those load separately.
"""
from __future__ import annotations

import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC_CSS = ROOT / "static" / "css"
OUT = STATIC_CSS / "home-page-bundle.css"

SOURCES = [
    "home.css",
    "home-figma/home-figma.css",
    "components/clients-marquee.css",
    "home-figma/home-figma-cz.css",
]


def main() -> None:
    parts: list[str] = [
        "/* AUTO-GENERATED by scripts/build_home_css.py — do not edit by hand. */\n"
        "/* Source order matches templates/pages/home.html DEBUG page_css. */\n"
    ]
    for rel in SOURCES:
        path = STATIC_CSS / rel
        if not path.is_file():
            raise SystemExit(f"Missing CSS source: {path}")
        parts.append(f"\n/* ===== {rel} ===== */\n")
        css = path.read_text(encoding="utf-8")
        base = posixpath.dirname(rel)
        if base:
            # Rebase relative url(...) from the source subdir to static/css/.
            def _rebase(m: re.Match) -> str:
                q, u = m.group(1), m.group(2)
                if re.match(r"^(data:|https?:|/|#)", u):
                    return m.group(0)
                return f"url({q}{posixpath.normpath(posixpath.join(base, u))}{q})"
            css = re.sub(r"url\(\s*(['\"]?)([^'\")]+)\1\s*\)", _rebase, css)
        parts.append(css)
        if not parts[-1].endswith("\n"):
            parts.append("\n")

    OUT.write_text("".join(parts), encoding="utf-8")
    size = OUT.stat().st_size
    print(f"Wrote {OUT.relative_to(ROOT)} ({size / 1024:.1f} KiB) from {len(SOURCES)} files")


if __name__ == "__main__":
    main()
